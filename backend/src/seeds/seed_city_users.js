async function seed() {
  console.log(`Starting seeding of ${USERS_DATA.length} authentic profiles...`);
  const salt = await bcrypt.genSalt(10);
  const password_hash = await bcrypt.hash('Password@123', salt);

  let createdCount = 0;
  for (const item of USERS_DATA) {
    const existing = await User.findOne({ where: { email: item.email } });
    if (existing) {
      console.log(`User already exists: ${item.email}, skipping.`);
      continue;
    }

    const user = await User.create({
      name: item.name,
      email: item.email,
      phone: item.phone,
      gender: item.gender,
      city: item.city,
      bio: item.bio,
      password_hash,
      role: 'user',
      is_companion: true,
      is_verified: true,
      is_payment_verified: true,
      is_active: true,
      avatar_url: null // To be added by admin using Admin Panel
    });

    await CompanionProfile.create({
      user_id: user.id,
      hourly_rate: item.hourly_rate,
      event_rate: item.event_rate,
      tagline: item.tagline,
      languages: item.languages,
      interests: item.interests,
      available_days: ['Fri', 'Sat', 'Sun'],
      is_listed: true,
      avg_rating: (4.7 + Math.random() * 0.3).toFixed(2),
      total_bookings: Math.floor(5 + Math.random() * 20)
    });

    createdCount++;
  }

  console.log(`\n========================================`);
  console.log(`✅ Successfully seeded ${createdCount} authentic profiles into database!`);
  console.log(`- Hyderabad: 50 (40 Female, 10 Male)`);
  console.log(`- Bangalore: 10 (8 Female, 2 Male)`);
  console.log(`- Mumbai:    15 (12 Female, 3 Male)`);
  console.log(`- Chennai:   15 (12 Female, 3 Male)`);
  console.log(`- Ratio:     4:1 Female to Male (72 F : 18 M)`);
  console.log(`- All have companion profiles, authentic regional names, rates & bios.`);
  console.log(`- Default password for all: Password@123`);
  console.log(`========================================\n`);

  process.exit(0);
}

